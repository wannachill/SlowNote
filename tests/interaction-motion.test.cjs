test('confirmation runs original callback exactly once, cancellation and unload never delete', async () => {
  const {page}=front('baby');let accepted=0,cancelled=0
  page.confirmDanger({title:'删除宝宝档案',content:'将删除该宝宝的档案及其关联记录，此操作不可恢复。',success:r=>{r.confirm?accepted++:cancelled++}})
  assert.equal(accepted,0);page.cancelDanger();page.acceptDanger()
  await wait(420);assert.equal(accepted,0);assert.equal(cancelled,1)
  page.confirmDanger({title:'删除宝宝档案',success:r=>{if(r.confirm)accepted++}})
  page.acceptDanger();page.acceptDanger();await wait(420);assert.equal(accepted,1)
  page.confirmDanger({title:'删除宝宝档案',success:()=>accepted++})
  page.acceptDanger();page.onUnload();await wait(420);assert.equal(accepted,1)
})
test('theme reveal preserves immediate local preference and survives rapid color toggles', async () => {
  const theme=require('../miniprogram/utils/theme')
  const f=front('theme'),{page,app,wx,storage}=f
  wx.getWindowInfo=()=>({windowWidth:375,windowHeight:812})
  app.setTheme=async pref=>{storage.slownote_theme_pref=pref;app.palette=theme.resolve(pref);page.applyTheme();return true}
  page.captureThemeOrigin({touches:[{clientX:325,clientY:120}]})
  await page.changeTheme({color:'pink'})
  assert.equal(storage.slownote_theme_pref.color,'pink')
  assert.equal(page.data.themeClass,'theme-color-pink');assert.equal(page.data.themeBefore.themeClass,'theme-color-blue')
  assert.match(page.data.themeRevealStyle,/--reveal-x:325px;/)
  assert.equal(Object.hasOwn(page.data,'modeIndex'),false)
  await page.changeTheme({color:'dark'});assert.equal(storage.slownote_theme_pref.color,'dark')
  assert.equal(page.data.themeClass,'theme-color-dark mode-dark');assert.equal(page.data.themeBefore.themeClass,'theme-color-pink')
  await page.changeTheme({color:'blue'});assert.equal(storage.slownote_theme_pref.color,'blue')
  assert.equal(page.data.themeClass,'theme-color-blue');assert.equal(page.data.themeBefore.themeClass,'theme-color-dark mode-dark')
  await wait(420);assert.equal(page.data.themeBefore,null);assert.equal(page.data.themeReveal,false)
  page.onHide()
})
