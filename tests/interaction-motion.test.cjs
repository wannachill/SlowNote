test('all new WXML handlers resolve on their host page and templates compile as presentation',()=>{
  const root=path.join(__dirname,'../miniprogram')
  for(const name of fs.readdirSync(path.join(root,'pages'))){
    const {page}=front(name)
    let wxml=fs.readFileSync(path.join(root,'pages',name,'index.wxml'),'utf8')
    for(const m of wxml.matchAll(/<(?:include|import) src="([^"]+)"/g))wxml+='\n'+fs.readFileSync(path.resolve(root,'pages',name,m[1]),'utf8')
    for(const m of wxml.matchAll(/(?:bind|catch)(?:touchstart|touchmove|touchend|touchcancel|longpress|tap|change)="([^"]+)"/g)){
      if(m[1].startsWith('{{'))continue
      assert.equal(typeof page[m[1]],'function',name+': '+m[1])
    }
  }
})
